"""Seed the binding manifest and generate everything derived from it (RP-11).

seed      keep bindings/manifest.json in step with upstream/api-surface.json:
          add new declarations as unreviewed, reset changed ones, drop removed
          ones. Never promotes a status.
generate  write the derived files below from the manifest, deterministically.
check     regenerate in memory and fail if any derived file differs: it was
          edited by hand, or the manifest changed without regenerating.

Derived files (never edit them):
  bindings/generated/mapping.json           C++ -> Python map of mapped records
  native/bindings/generated/registry.{hpp,cpp}  registration scaffold calling
                                            the hand-written adapters in
                                            native/bindings/<family>.cpp
  docs/reference/coverage.md                coverage report
  docs/reference/callback-paths.md          every public virtual's domain and Python path/blocker
  docs/reference/crosswalk.md, crosswalk/   C++ -> Python crosswalk of every declaration, by family
"""

import hashlib
import json
import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import cyclopts

sys.path.insert(0, str(Path(__file__).resolve().parent))
import binding_manifest as bm

app = cyclopts.App(help=__doc__)
GENERATED_NOTE = "Generated by bin/generate_bindings.py from bindings/manifest.json; do not edit."


def digest(manifest_text: str, inputs: bm.Inputs) -> str:
    return hashlib.sha256((manifest_text + inputs.inventory_sha256).encode()).hexdigest()[:16]


def mapped(manifest: dict[str, Any]) -> list[dict[str, Any]]:
    return [r for r in manifest["entries"] if r["python"]]


def bound(manifest: dict[str, Any]) -> list[dict[str, Any]]:
    return [r for r in manifest["entries"] if r["status"] in bm.BOUND]


# Scene, RackScrollWidget and RackWidget have PRIVATE constructors, and only CableWidget's constructor
# makes a usable PlugWidget, so no plugin subclasses them (the manifest notes cite the source lines).
HOST_ONLY_APP_WIDGETS = ("PlugWidget", "RackScrollWidget", "RackWidget", "Scene")


# RP-22F: the laboratory class whose subclass overrides each driver/device virtual, by Rack's class.
LABORATORY_DRIVERS = {
    "rack::audio::Driver::": "AudioDriver",
    "rack::audio::Device::": "AudioDevice",
    "rack::midi::Driver::": "MidiDriver",
    "rack::midi::Device::": "MidiInputDevice/MidiOutputDevice",
    "rack::midi::Input::": "MidiInput",
    "rack::midi::InputQueue::": "MidiInputQueue",
}


def callback_execution(record: dict[str, Any], entry: dict[str, Any]) -> str:
    """Describe execution, not just callability: native adapters are not Python overrides."""
    strategy = record["callback"]
    name = entry["name"]
    python = record["python"] or {}
    path = python.get("facade") or python.get("raw")
    if record["status"] not in bm.BOUND:
        return "**Full-release blocker**: " + (record.get("notes") or "No semantic Python mapping yet.")
    if strategy == "lifecycle":
        return "Owner/GC deletion, not a Python destructor override; lifetime mapping: " + str(path)
    if strategy == "value":
        return "Exception/value translation, not a Python override: " + str(path)
    if name.startswith("rack::engine::Module::"):
        method = name.rsplit("::", 1)[-1]
        method = re.sub(r"(?<!^)(?=[A-Z])", "_", method).lower()
        if method in {"to_json", "from_json"}:
            method = "module_" + method
        return "Synchronous offline override: rackpy.laboratory.ModuleClass." + method + "; Bench/main thread only."
    if strategy == "mixed":
        owner = "ParamQuantity" if "ParamQuantity::" in name else "Quantity"
        method = str(python["raw"]).rsplit(".", 1)[-1]
        return f"Synchronous offline override: rackpy.laboratory.{owner}.{method}; main thread only."
    if strategy == "engine":
        if "MidiGenerator::" in name:
            return (
                "Synchronous offline override: rackpy.laboratory.MidiGenerator[N].on_message; "
                "same-object reentry dispatches as in C++ (shared resolver, 64-call bound)."
            )
        if "OutputDevice::" in name:
            return (
                "Synchronous offline override: rackpy.laboratory.MidiOutputDevice.send_message "
                "via a connected Python-made Output."
            )
    if strategy == "driver":
        if "rack::audio::Port::" in name:
            return (
                f"Synchronous override: {path}, only on a Python-driven device; "
                "Rack threads use native/queued adapters."
            )
        laboratory_class = next((c for prefix, c in LABORATORY_DRIVERS.items() if name.startswith(prefix)), None)
        if laboratory_class is None:
            return "**Full-release blocker**: native/queued adapter only; no synchronous laboratory Python override."
        method = str(python["raw"]).rsplit(".", 1)[-1]
        caller = (
            "RackPy's repetition of Rack's Port::setDriverId in AudioDriver.connect (src/audio.cpp:116), not Rack's own"
            if name == "rack::audio::Driver::getDefaultDeviceId"
            else "Rack's own port code"
        )
        return (
            f"Synchronous offline override: rackpy.laboratory.{laboratory_class}.{method}, called by {caller} for a "
            "connected Python-made port; main thread only. Production: native configured/queued adapter."
        )
    if strategy == "ui" and any(name.startswith(f"rack::app::{owner}::") for owner in HOST_ONLY_APP_WIDGETS):
        return (
            f"Call on Rack's own instance: {path} (borrowed host view). No override path: only Rack makes usable "
            "instances of this class (RP-28F decision, owner-approved 2026-10-26; docs/coverage.md policy 11)."
        )
    if name.startswith("rack::app::CableWidget::"):
        method = re.sub(r"(?<!^)(?=[A-Z])", "_", name.rsplit("::", 1)[-1]).lower()
        return (
            f"Synchronous UI override: rackpy.raw.app.CableWidget.{method}; "
            "Python-created subclass, not HostCableWidget."
        )
    return (
        f"Main-thread mapping: {path}; see per-symbol semantics below "
        "(callable/adapters are not automatically overrides)."
    )


def callback_paths(manifest: dict[str, Any], inputs: bm.Inputs) -> str:
    """Join the RP-06 classifier's exact denominator to the binding manifest."""
    records = {r["id"]: r for r in manifest["entries"]}
    rules = bm.load_json(bm.CALLBACK_RULES)
    rows = bm.callback_matrix().classify(inputs.inventory["entries"], rules["rules"])
    out = [
        "# Public virtual execution paths",
        "",
        f"**{GENERATED_NOTE}** Domain classification: `bin/callback-matrix` and `upstream/callback-rules.json`.",
        "",
        f"All **{len(rows)} public virtual declarations**, including deprecated overloads, "
        "destructors and value virtuals.",
        "The denominator is unchanged. No entry is promoted to verified by this report.",
        "",
        "**Laboratory means explicitly enabled, offline and main-thread only, never Rack's engine/driver threads.**",
        "See [Callbacks and the laboratory](../explanation/callbacks.md) for restrictions, fidelity gaps and",
        "re-entrant dispatch (fixed by `tk-rackpy-trampolines-suppress-same-object-re-entra-0abce9`).",
        "Native configured/queued driver adapters are production paths; their synchronous Python paths are the",
        "laboratory drivers and devices of RP-22F (`tk-rackpy-22f-laboratory-python-paths-for-audio-and-65ccf3`). "
        "A callable name is not proof of an override.",
        "No plugin can subclass Rack's Scene, RackScrollWidget or RackWidget (PRIVATE constructors) or make a "
        "usable PlugWidget subclass, so their UI virtuals map to calls on Rack's own instances through borrowed "
        "host views (RP-28F decision, owner-approved 2026-10-26: "
        "`tk-rackpy-28f-python-subclass-trampolines-for-plugw-154b61`).",
        "Per-symbol semantics below retain the manifest's adapter restrictions; implemented is not verified.",
        "",
        "## Execution domains",
        "",
        "| Domain | Legitimate Rack execution domain |",
        "| --- | --- |",
    ]
    out += [f"| `{key}` | {value} |" for key, value in rules["strategies"].items()]
    out += [
        "",
        "## Every declaration",
        "",
        "| Upstream ID | Domain | Status | Python execution path or blocker | "
        "Raw / facade names | Manifest semantics |",
        "| --- | --- | --- | --- | --- | --- |",
    ]

    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    for row in rows:
        record = records[row["id"]]
        python = record["python"] or {}
        paths = " / ".join(f"`{p}`" for p in (python.get("raw"), python.get("facade")) if p) or "—"
        cells = [
            f"`{row['id']}`",
            f"`{row['strategy']}`",
            record["status"],
            callback_execution(record, inputs.index[row["id"]]),
            paths,
            record.get("notes") or "—",
        ]
        out.append("| " + " | ".join(cell(c) for c in cells) + " |")
    return "\n".join(out) + "\n"


CROSSWALK_STATUS = {
    "implemented": "bound",
    "verified": "verified",
    "excluded_internal": "excluded: Rack-internal",
    "unreviewed": "not reviewed (another platform)",
}


def crosswalk(manifest: dict[str, Any], inputs: bm.Inputs, repo: Path) -> dict[Path, str]:
    """The C++ -> Python crosswalk (RP-37): every manifest declaration's Python names and documentation, by family."""
    index = inputs.index
    folder = repo / "docs" / "reference" / "crosswalk"
    by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in manifest["entries"]:
        entry = index.get(r["id"])
        by_family[bm.family_of(inputs.inventory, entry) if entry else "unassigned"].append(r)

    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    headings: dict[str, set[str]] = {}

    def doc_link(ref: str) -> str:
        """A heading anchor is a link to the page; a `(label)=` target, a reference to the label."""
        path, _, anchor = ref.partition("#")
        rel = os.path.relpath(repo / path, folder)
        text = f"{Path(path).stem}{'#' + anchor if anchor else ''}"
        if path not in headings:
            page = (repo / path).read_text(encoding="utf-8")
            headings[path] = {bm.slug(m) for m in re.findall(r"^#{1,6}\s+(.+?)\s*$", page, re.MULTILINE)}
        if not anchor or anchor in headings[path]:
            return f"[{text}]({rel}{'#' + anchor if anchor else ''})"
        return f"{{ref}}`{text} <{anchor}>`"

    pages: dict[Path, str] = {}
    rows = []
    for family in sorted(by_family):
        slug = bm.FAMILY_SLUGS.get(family, family).replace("_", "-")
        records = sorted(by_family[family], key=lambda r: r["id"])
        counts: dict[str, int] = defaultdict(int)
        for r in records:
            counts[r["status"]] += 1
        rows.append((family, slug, len(records), counts))
        lines = [
            f"# {family.split(' ', 1)[-1].capitalize()}: C++ to Python",
            "",
            f"**{GENERATED_NOTE}** Back to the [crosswalk](../crosswalk.md).",
            "",
            "Each public declaration of this family in Rack's SDK, the Python name or names it has in RackPy, and "
            "where it is documented. *Bound* means implemented and tested on Linux x86_64, not `verified`.",
            "",
            "| C++ declaration | Kind | Status | Python | Documented in |",
            "| --- | --- | --- | --- | --- |",
        ]
        for r in records:
            kind, _, name = r["id"].partition(":")
            python = r["python"] or {}
            names = " / ".join(f"`{n}`" for n in (python.get("raw"), python.get("facade")) if n) or "—"
            docs = ", ".join(doc_link(ref) for ref in r.get("docs") or []) or "—"
            status = CROSSWALK_STATUS.get(r["status"], r["status"])
            lines.append("| " + " | ".join(cell(c) for c in (f"`{name}`", kind, status, names, docs)) + " |")
        pages[folder / f"{slug}.md"] = "\n".join(lines) + "\n"
    index_lines = [
        "# C++ to Python crosswalk",
        "",
        f"**{GENERATED_NOTE}**",
        "",
        "Every public declaration of Rack's SDK that RackPy accounts for, with its Python names (raw binding, "
        "then facade) and its documentation, from the same manifest as the [coverage report](coverage.md). "
        "Read the linked pages for restrictions, errors and defaults: a name alone does not say how to use it. "
        "[Coming from Rack's C++ API](../how-to/migrate-from-cpp.md) explains the naming rules.",
        "",
        "| Family | Declarations | Bound | Excluded (Rack-internal) | Not reviewed |",
        "| --- | --- | --- | --- | --- |",
    ]
    for family, slug, total, counts in rows:
        index_lines.append(
            f"| [{family}](crosswalk/{slug}.md) | {total} | {counts['implemented'] + counts['verified']} | "
            f"{counts['excluded_internal']} | {counts['unreviewed']} |"
        )
    index_lines += ["", "```{toctree}", ":hidden:", "", *[f"crosswalk/{slug}" for _, slug, _, _ in rows], "```"]
    pages[repo / "docs" / "reference" / "crosswalk.md"] = "\n".join(index_lines) + "\n"
    return pages


def generate_files(manifest: dict[str, Any], manifest_text: str, inputs: bm.Inputs, repo: Path) -> dict[Path, str]:
    """Every derived file and its content. Raises ManifestError for a manifest that must not be generated from."""
    index = inputs.index
    refused = [
        r["id"]
        for r in mapped(manifest)
        if r["locks_engine"] in {"exclusive", "shared"} and not r["python"].get("gil_release")
    ]
    if refused:
        raise bm.ManifestError(
            "these bindings take the engine lock but do not release the GIL (ADR 003, decision 2): "
            + ", ".join(refused)
        )
    stamp = digest(manifest_text, inputs)
    by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in bound(manifest):
        by_family[bm.family_of(inputs.inventory, index[r["id"]])].append(r)
    families = [f for f in bm.FAMILY_SLUGS if by_family.get(f)]
    for family in families:
        adapter = repo / "native" / "bindings" / f"{bm.FAMILY_SLUGS[family]}.cpp"
        if not adapter.is_file():
            raise bm.ManifestError(
                f"family {family!r} has bound records but no hand-written adapter {adapter.relative_to(repo)}"
            )

    mapping = {
        "note": GENERATED_NOTE,
        "inputs": stamp,
        "entries": [
            {
                "id": r["id"],
                "status": r["status"],
                "raw": r["python"].get("raw"),
                "facade": r["python"].get("facade"),
                "kind": r["python"].get("kind"),
            }
            for r in mapped(manifest)
        ],
    }

    header = [
        f"// {GENERATED_NOTE}",
        f"// Inputs: {stamp}",
        "#pragma once",
        "#include <pybind11/pybind11.h>",
        "",
        "namespace rackpy {",
        "namespace bindings {",
        "",
        "/** Bind every family that has bound records into `raw` (rackpy.raw), which mirrors the rack namespace. */",
        "void registerAll(pybind11::module_& raw);",
        "",
    ]
    if families:
        header.append("// Hand-written adapters, one per family, in native/bindings/<family>.cpp:")
        header += [f"void bind_{bm.FAMILY_SLUGS[f]}(pybind11::module_ raw);" for f in families]
    else:
        header.append("// No family has bound records yet, so there are no adapters to call.")
    header += ["", "}  // namespace bindings", "}  // namespace rackpy", ""]

    source = [
        f"// {GENERATED_NOTE}",
        f"// Inputs: {stamp}",
        '#include "registry.hpp"',
        "",
        "namespace rackpy {",
        "namespace bindings {",
        "",
        "void registerAll(pybind11::module_& raw) {",
    ]
    for family in families:
        slug = bm.FAMILY_SLUGS[family]
        source.append(f"\t// {family}: {len(by_family[family])} bound record(s)")
        for r in sorted(by_family[family], key=lambda r: r["id"]):
            source.append(f"\t//   {r['id']} -> {r['python'].get('raw') or '(no runtime meaning)'}")
        source.append(f"\tbind_{slug}(raw);")
    if not families:
        source.append("\t(void) raw;  // nothing is bound yet")
    source += ["}", "", "}  // namespace bindings", "}  // namespace rackpy", ""]

    report = bm.markdown_report(bm.report(inputs, manifest))
    boundary = [entry for entry in inputs.inventory["entries"] if entry["kind"] == "boundary_constant"]
    declarations = [f"// {GENERATED_NOTE}"]
    stubs: dict[str, list[str]] = {"glfw": [], "blendish": []}
    for entry in boundary:
        name = entry["name"]
        namespace = "glfw" if entry["boundary"] == "input" else "blendish"
        declarations.append(f'{namespace}.attr("{name}") = py::int_(static_cast<int>({name}));')
        stubs[namespace].append(f"{name}: int")
    return {
        repo / "bindings" / "generated" / "mapping.json": json.dumps(mapping, indent=2, sort_keys=True) + "\n",
        repo / "native" / "bindings" / "generated" / "registry.hpp": "\n".join(header),
        repo / "native" / "bindings" / "generated" / "registry.cpp": "\n".join(source),
        repo / "docs" / "reference" / "coverage.md": report,
        repo / "docs" / "reference" / "callback-paths.md": callback_paths(manifest, inputs),
        repo / "native" / "bindings" / "generated" / "boundary_constants.inc": "\n".join(declarations) + "\n",
        **crosswalk(manifest, inputs, repo),
        **{
            repo / "src" / "rackpy" / "raw" / f"{module}.pyi": (f"# {GENERATED_NOTE}\n" + "\n".join(names) + "\n")
            for module, names in stubs.items()
        },
    }


def load(manifest: Path) -> tuple[dict[str, Any], str]:
    text = manifest.read_text(encoding="utf-8") if manifest.exists() else ""
    if not text:
        raise bm.ManifestError(f"{manifest} does not exist; create it with bin/generate_bindings.py seed")
    data: dict[str, Any] = bm.load_json(manifest)
    return data, text


@app.command
def seed(*, update: bool = False, manifest: Path = bm.MANIFEST) -> None:
    """Create bindings/manifest.json, or with --update bring it in step with the inventory."""
    inputs = bm.load_inputs()
    existing = None
    if manifest.exists():
        if not update:
            raise SystemExit(f"{manifest} exists; pass --update to bring it in step with the inventory")
        existing = bm.load_json(manifest)
    data, changes = bm.seed(inputs, existing)
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(bm.dumps(data), encoding="utf-8")
    statuses = {s: sum(1 for r in data["entries"] if r["status"] == s) for s in bm.STATUSES}
    print(f"{len(data['entries'])} records: " + ", ".join(f"{k} {v}" for k, v in statuses.items() if v))
    print(f"added {len(changes.added)}, removed {len(changes.removed)}, reset to unreviewed {len(changes.reset)}")
    for ident in changes.removed:
        print(f"  removed: {ident}")
    for ident in changes.reset:
        print(f"  reset:   {ident}")


@app.command
def generate(*, manifest: Path = bm.MANIFEST) -> None:
    """Write every derived file from the manifest."""
    data, text = load(manifest)
    inputs = bm.load_inputs()
    for path, content in generate_files(data, text, inputs, bm.REPO).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(bm.REPO)}")


@app.command
def check(*, manifest: Path = bm.MANIFEST) -> None:
    """Fail if a derived file differs from what the manifest generates."""
    data, text = load(manifest)
    inputs = bm.load_inputs()
    stale = [
        path.relative_to(bm.REPO).as_posix()
        for path, content in generate_files(data, text, inputs, bm.REPO).items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if stale:
        raise SystemExit(
            "generated files are stale or were edited by hand: "
            + ", ".join(stale)
            + "\nrun bin/generate_bindings.py generate (and fix the manifest, not the generated files)"
        )
    print("ok: generated files match bindings/manifest.json")


if __name__ == "__main__":
    try:
        app()
    except bm.ManifestError as e:
        raise SystemExit(f"error: {e}") from None
