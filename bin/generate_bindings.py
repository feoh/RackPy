"""Seed the binding manifest and generate everything derived from it (RP-11).

seed      keep bindings/manifest.json in step with upstream/api-surface.json:
          add new declarations as unreviewed, reset changed ones, drop removed
          ones. Never promotes a status.
generate  write the derived files below from the manifest, deterministically.
check     regenerate in memory and fail if any derived file differs: it was
          edited by hand, or the manifest changed without regenerating.

Derived files (never edit them):
  bindings/generated/mapping.json           C++ -> Python map of mapped records
  native/bindings/generated/registry.{hpp,cpp}  registration scaffold calling
                                            the hand-written adapters in
                                            native/bindings/<family>.cpp
  docs/reference/coverage.md                coverage report
"""

import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import cyclopts

sys.path.insert(0, str(Path(__file__).resolve().parent))
import binding_manifest as bm

app = cyclopts.App(help=__doc__)
GENERATED_NOTE = "Generated by bin/generate_bindings.py from bindings/manifest.json; do not edit."


def digest(manifest_text: str, inputs: bm.Inputs) -> str:
    return hashlib.sha256((manifest_text + inputs.inventory_sha256).encode()).hexdigest()[:16]


def mapped(manifest: dict[str, Any]) -> list[dict[str, Any]]:
    return [r for r in manifest["entries"] if r["python"]]


def bound(manifest: dict[str, Any]) -> list[dict[str, Any]]:
    return [r for r in manifest["entries"] if r["status"] in bm.BOUND]


def generate_files(manifest: dict[str, Any], manifest_text: str, inputs: bm.Inputs, repo: Path) -> dict[Path, str]:
    """Every derived file and its content. Raises ManifestError for a manifest that must not be generated from."""
    index = inputs.index
    refused = [
        r["id"]
        for r in mapped(manifest)
        if r["locks_engine"] in {"exclusive", "shared"} and not r["python"].get("gil_release")
    ]
    if refused:
        raise bm.ManifestError(
            "these bindings take the engine lock but do not release the GIL (ADR 003, decision 2): "
            + ", ".join(refused)
        )
    stamp = digest(manifest_text, inputs)
    by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in bound(manifest):
        by_family[bm.family_of(inputs.inventory, index[r["id"]])].append(r)
    families = [f for f in bm.FAMILY_SLUGS if by_family.get(f)]
    for family in families:
        adapter = repo / "native" / "bindings" / f"{bm.FAMILY_SLUGS[family]}.cpp"
        if not adapter.is_file():
            raise bm.ManifestError(
                f"family {family!r} has bound records but no hand-written adapter {adapter.relative_to(repo)}"
            )

    mapping = {
        "note": GENERATED_NOTE,
        "inputs": stamp,
        "entries": [
            {
                "id": r["id"],
                "status": r["status"],
                "raw": r["python"].get("raw"),
                "facade": r["python"].get("facade"),
                "kind": r["python"].get("kind"),
            }
            for r in mapped(manifest)
        ],
    }

    header = [
        f"// {GENERATED_NOTE}",
        f"// Inputs: {stamp}",
        "#pragma once",
        "#include <pybind11/pybind11.h>",
        "",
        "namespace rackpy {",
        "namespace bindings {",
        "",
        "/** Bind every family that has bound records into `raw` (rackpy.raw), which mirrors the rack namespace. */",
        "void registerAll(pybind11::module_& raw);",
        "",
    ]
    if families:
        header.append("// Hand-written adapters, one per family, in native/bindings/<family>.cpp:")
        header += [f"void bind_{bm.FAMILY_SLUGS[f]}(pybind11::module_ raw);" for f in families]
    else:
        header.append("// No family has bound records yet, so there are no adapters to call.")
    header += ["", "}  // namespace bindings", "}  // namespace rackpy", ""]

    source = [
        f"// {GENERATED_NOTE}",
        f"// Inputs: {stamp}",
        '#include "registry.hpp"',
        "",
        "namespace rackpy {",
        "namespace bindings {",
        "",
        "void registerAll(pybind11::module_& raw) {",
    ]
    for family in families:
        slug = bm.FAMILY_SLUGS[family]
        source.append(f"\t// {family}: {len(by_family[family])} bound record(s)")
        for r in sorted(by_family[family], key=lambda r: r["id"]):
            source.append(f"\t//   {r['id']} -> {r['python'].get('raw') or '(no runtime meaning)'}")
        source.append(f"\tbind_{slug}(raw);")
    if not families:
        source.append("\t(void) raw;  // nothing is bound yet")
    source += ["}", "", "}  // namespace bindings", "}  // namespace rackpy", ""]

    report = bm.markdown_report(bm.report(inputs, manifest))
    return {
        repo / "bindings" / "generated" / "mapping.json": json.dumps(mapping, indent=2, sort_keys=True) + "\n",
        repo / "native" / "bindings" / "generated" / "registry.hpp": "\n".join(header),
        repo / "native" / "bindings" / "generated" / "registry.cpp": "\n".join(source),
        repo / "docs" / "reference" / "coverage.md": report,
    }


def load(manifest: Path) -> tuple[dict[str, Any], str]:
    text = manifest.read_text(encoding="utf-8") if manifest.exists() else ""
    if not text:
        raise bm.ManifestError(f"{manifest} does not exist; create it with bin/generate_bindings.py seed")
    data: dict[str, Any] = bm.load_json(manifest)
    return data, text


@app.command
def seed(*, update: bool = False, manifest: Path = bm.MANIFEST) -> None:
    """Create bindings/manifest.json, or with --update bring it in step with the inventory."""
    inputs = bm.load_inputs()
    existing = None
    if manifest.exists():
        if not update:
            raise SystemExit(f"{manifest} exists; pass --update to bring it in step with the inventory")
        existing = bm.load_json(manifest)
    data, changes = bm.seed(inputs, existing)
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(bm.dumps(data), encoding="utf-8")
    statuses = {s: sum(1 for r in data["entries"] if r["status"] == s) for s in bm.STATUSES}
    print(f"{len(data['entries'])} records: " + ", ".join(f"{k} {v}" for k, v in statuses.items() if v))
    print(f"added {len(changes.added)}, removed {len(changes.removed)}, reset to unreviewed {len(changes.reset)}")
    for ident in changes.removed:
        print(f"  removed: {ident}")
    for ident in changes.reset:
        print(f"  reset:   {ident}")


@app.command
def generate(*, manifest: Path = bm.MANIFEST) -> None:
    """Write every derived file from the manifest."""
    data, text = load(manifest)
    inputs = bm.load_inputs()
    for path, content in generate_files(data, text, inputs, bm.REPO).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(bm.REPO)}")


@app.command
def check(*, manifest: Path = bm.MANIFEST) -> None:
    """Fail if a derived file differs from what the manifest generates."""
    data, text = load(manifest)
    inputs = bm.load_inputs()
    stale = [
        path.relative_to(bm.REPO).as_posix()
        for path, content in generate_files(data, text, inputs, bm.REPO).items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if stale:
        raise SystemExit(
            "generated files are stale or were edited by hand: "
            + ", ".join(stale)
            + "\nrun bin/generate_bindings.py generate (and fix the manifest, not the generated files)"
        )
    print("ok: generated files match bindings/manifest.json")


if __name__ == "__main__":
    try:
        app()
    except bm.ManifestError as e:
        raise SystemExit(f"error: {e}") from None
